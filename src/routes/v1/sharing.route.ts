import { Router } from "express";
import { z } from "zod";
import { authMiddleware } from "../../middleware/auth.js";
import { accountMiddleware } from "../../middleware/account.js";
import { requireRole } from "../../middleware/role.js";
import { validate } from "../../middleware/validate.js";
import { wrongAccountGuard } from "../../middleware/wrong_account.js";
import { sharingController } from "../../container.js";
const router = Router();
router.use(authMiddleware);
router.use(accountMiddleware);
router.use("/:id", wrongAccountGuard);
router.get("/:id/members", requireRole("owner"), sharingController.members);
router.get("/:id/invites", requireRole("owner"), sharingController.listInvites);
router.post("/:id/invites", requireRole("owner"), validate(z.object({ email: z.email().max(254), role: z.enum(["editor", "viewer"]) }).strict()), sharingController.createInvite);
router.delete("/:id/invites/:token", requireRole("owner"), sharingController.revokeInvite);
router.patch("/:id/members/:uid", requireRole("owner"), validate(z.object({ role: z.enum(["owner", "editor", "viewer"]) }).strict()), sharingController.changeRole);
router.delete("/:id/members/:uid", requireRole("owner"), sharingController.removeMember);
router.post("/:id/leave", requireRole("viewer"), sharingController.leave);
router.post("/:id/transfer-ownership", requireRole("owner"), validate(z.object({ userId: z.string().min(1).max(128) }).strict()), sharingController.transferOwnership);
export default router;
